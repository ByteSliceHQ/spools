/**
 * Compiles a validated CRM config into a Prisma 8 schema (PSL): the system
 * tables (src/server/store/tables.ts), one table per object and one per
 * many-to-many relation (src/server/store/objects.ts). Pure function;
 * scripts/crm-gen.ts does the file I/O.
 *
 * Every table is marked `@@rls` with no policies: the app connects as a
 * privileged role (which bypasses RLS), while Supabase's Data API roles get no
 * rows. scripts/db-harden.ts additionally revokes those roles' table privileges.
 */
import { allTables } from '../server/store/schema-sql'
import { type AnyTable, type Column, columnName, type Kind } from '../server/store/table'
import type { CrmConfig } from './config-schema'

const SCALARS: Record<Kind, string> = {
  text: 'String',
  integer: 'Int',
  float: 'Float',
  decimal: 'NumericString(14, 2)',
  boolean: 'Boolean',
  date: 'DateString',
  timestamp: 'DateTime',
}

const ON_DELETE = { restrict: 'Restrict', 'set null': 'SetNull', cascade: 'Cascade' } as const

const doc = (words: string | undefined, indent = '') =>
  (words ?? '')
    .split('\n')
    .filter(Boolean)
    .map((line) => `${indent}/// ${line}`)

const mapped = (key: string) => (columnName(key) === key ? '' : ` @map("${columnName(key)}")`)

function columnLine(key: string, c: Column, primary: boolean): string {
  if (c.auto === 'id') {
    return `  ${key} String @id @onCreate(uuid())${mapped(key)}`
  }

  if (c.auto === 'created') {
    return `  ${key} DateTime @default(now()) @onCreate(now())${mapped(key)}`
  }

  if (c.auto === 'updated') {
    return `  ${key} temporal.UpdatedAt${mapped(key)}`
  }

  const fallback = c.default === undefined ? '' : ` @default(${JSON.stringify(c.default)})`
  return `  ${key} ${SCALARS[c.kind]}${c.nullable ? '?' : ''}${primary ? ' @id' : ''}${fallback}${mapped(key)}`
}

/** One table as a Prisma model. */
function model(table: AnyTable): string {
  const lines: string[] = []

  for (const [key, c] of Object.entries(table.columns)) {
    lines.push(...doc(c.doc, '  '), columnLine(key, c, key === table.primary))
  }

  for (const [key, relation] of Object.entries(table.relations)) {
    const target = relation.table()

    if (relation.kind === 'many') {
      const forward = Object.entries(target.relations).find(
        ([, r]) => r.kind === 'one' && r.column === relation.column && r.table() === table,
      )

      lines.push(`  ${key} ${target.model}[] @relation("${target.model}_${forward?.[0]}")`)
      continue
    }

    const opt = table.columns[relation.column]?.nullable ? '?' : ''
    const onDelete = ON_DELETE[relation.onDelete ?? 'set null']

    lines.push(
      `  ${key} ${target.model}${opt} @relation("${table.model}_${key}", fields: [${relation.column}], references: [id], onDelete: ${onDelete})`,
    )
  }

  const rules = [
    ...table.unique.map((keys) => `  @@unique([${keys.join(', ')}])`),
    ...table.indexes.map((keys) => `  @@index([${keys.join(', ')}])`),
  ]

  if (table.search) {
    const [first, ...rest] = table.search.columns

    rules.push(
      `  @@fullTextIndex([${[`[${first}]`, ...rest].join(', ')}], name: "${table.search.name}")`,
    )
  }

  rules.push(`  @@map("${table.name}")`, '  @@rls')
  return [...doc(table.doc), `model ${table.model} {`, ...lines, '', ...rules, '}'].join('\n')
}

/** The Prisma schema for a config, and what the config asks for that the schema can't give yet. */
export type GeneratedPrisma = { schema: string; warnings: string[] }

export function generatePrisma(
  cfg: CrmConfig,
  adapters: readonly { tables?: readonly AnyTable[] }[] = [],
): GeneratedPrisma {
  const warnings = Object.entries(cfg.objects).flatMap(([objectKey, obj]) =>
    Object.entries(obj.fields)
      .filter(([, field]) => field.encrypted)
      .map(
        ([key, field]) =>
          `${objectKey}.${key} is marked encrypted: "${field.encrypted}" but is stored as PLAINTEXT ` +
          `(@cipherstash/stack-prisma does not support Prisma 8 yet)`,
      ),
  )

  const models = allTables(cfg, adapters).map(model)

  const schema = `// use prisma-8
// GENERATED by scripts/crm-gen.ts from crm.config.json. Do not edit by hand.

${models.join('\n\n')}
`

  return { schema, warnings }
}
